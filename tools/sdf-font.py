#!/usr/bin/env python3
"""Writes sdf_font.h: signed distance fields of Inter Display
ExtraBold glyphs, so the native games can draw smooth text at any size.

Inter is (c) The Inter Project Authors, SIL Open Font License 1.1.
Needs Pillow and NumPy. Usage: python3 tools/sdf-font.py [path/to/InterDisplay-ExtraBold.otf]
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter/InterDisplay-ExtraBold.otf"
CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+-.,:!?'/%()^<>"
EM = 40          # glyph size in the stored fields
SUPER = 8        # the outline is found at EM * SUPER and sampled down
SPREAD = 5.0     # distance range stored, in field pixels, either side of the edge
PAD = 4

font = ImageFont.truetype(FONT, EM * SUPER)
glyphs, data = [], bytearray()

for ch in CHARS:
    adv = font.getlength(ch) / SUPER
    if ch == " ":
        glyphs.append((ch, 0, 0, 0, 0, adv, 0))
        continue
    l, t, r, b = font.getbbox(ch)
    hi = Image.new("L", (r - l + 2 * PAD * SUPER, b - t + 2 * PAD * SUPER), 0)
    ImageDraw.Draw(hi).text((PAD * SUPER - l, PAD * SUPER - t), ch, font=font, fill=255)
    a = np.asarray(hi) > 127
    # edge pixels: inside pixels with an outside neighbour, and the reverse
    p = np.pad(a, 1)
    nb = p[:-2, 1:-1] ^ a | p[2:, 1:-1] ^ a | p[1:-1, :-2] ^ a | p[1:-1, 2:] ^ a
    ey, ex = np.nonzero(nb)
    ey = (ey + 0.5) / SUPER
    ex = (ex + 0.5) / SUPER
    w, h = -(-hi.width // SUPER), -(-hi.height // SUPER)
    out = np.zeros((h, w), dtype=np.uint8)
    for y in range(h):
        cy = y + 0.5
        cx = np.arange(w) + 0.5
        d = np.sqrt(((cx[:, None] - ex[None, :]) ** 2) + ((cy - ey[None, :]) ** 2)).min(axis=1)
        sy = min(int(cy * SUPER), a.shape[0] - 1)
        sx = np.minimum((cx * SUPER).astype(int), a.shape[1] - 1)
        inside = a[sy, sx]
        sd = np.where(inside, d, -d)  # positive inside
        out[y] = np.clip(128 + sd / SPREAD * 127, 0, 255).astype(np.uint8)
    glyphs.append((ch, len(data), w, h, l / SUPER - PAD, adv, t / SUPER - PAD))
    data += out.tobytes()

lines = [
    "/* Generated by tools/sdf-font.py, do not edit.",
    " * Signed distance fields of Inter Display ExtraBold glyphs.",
    " * Inter: (c) The Inter Project Authors, SIL Open Font License 1.1, https://rsms.me/inter/ */",
    f"#define SDF_EM {EM}",
    f"#define SDF_SPREAD {SPREAD}f",
    f'static const char SDF_CHARS[] = "{CHARS}";',
    "/* offset, w, h, left bearing, advance, top */",
    "static const struct { unsigned int off; unsigned char w, h; float left, adv, top; } SDF_GLYPHS[] = {",
]
for ch, off, w, h, left, adv, top in glyphs:
    lines.append(f"  {{{off}, {w}, {h}, {left:.3f}f, {adv:.3f}f, {top:.3f}f}},")
lines.append("};")
lines.append(f"static const unsigned char SDF_DATA[{len(data)}] = {{")
for i in range(0, len(data), 24):
    lines.append("  " + ",".join(str(v) for v in data[i : i + 24]) + ",")
lines.append("};")
Path(__file__).resolve().parent.parent.joinpath("sdf_font.h").write_text("\n".join(lines) + "\n")
print(f"{len(glyphs)} glyphs, {len(data)} bytes")
