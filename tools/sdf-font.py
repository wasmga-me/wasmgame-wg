#!/usr/bin/env python3
"""Writes sdf_font.h: signed distance fields of Inter Display
ExtraBold glyphs, so the native games can draw smooth text at any size.

With --extra, writes one game's extra glyphs instead: every character
outside sdf_font.h found in the string literals of the given source files
(its translations, and ASCII such as ~ @ { that it lacks): accented Latin, Greek and Cyrillic from Inter, kana
from Noto Sans JP, Hangul from Noto Sans KR and the rest (Han) from Noto
Sans SC, all ExtraBold, set on Inter's baseline. A file ending in .h is for wgfb.h (C games); one ending in
.rs is for the Rust engine (wg::Glyphs), with its fields in a .bin beside it.

Inter is (c) The Inter Project Authors, Noto Sans (c) Google LLC; all
SIL Open Font License 1.1. Needs Pillow and NumPy.
Usage: python3 tools/sdf-font.py [path/to/InterDisplay-ExtraBold.otf]
       python3 tools/sdf-font.py --extra OUT.h|OUT.rs SOURCE...
--extra downloads the Noto characters it needs from Google Fonts.
"""
import io
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

INTER = "/usr/share/fonts/opentype/inter/InterDisplay-ExtraBold.otf"
CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+-.,:!?'/%()^<>"
EM = 40          # glyph size in the stored fields
SUPER = 8        # the outline is found at EM * SUPER and sampled down
SPREAD = 5.0     # distance range stored, in field pixels, either side of the edge
PAD = 4
# Han characters are a full em tall; this brings them close to Inter's caps
EXTRA_SCALE = 0.86


def field(font, ch, dy=0):
    """(field bytes, w, h, left, advance, top) of one glyph; dy moves it down, in EM units."""
    adv = font.getlength(ch) / SUPER
    if ch.isspace():
        return b"", 0, 0, 0, adv, 0
    l, t, r, b = font.getbbox(ch)
    hi = Image.new("L", (r - l + 2 * PAD * SUPER, b - t + 2 * PAD * SUPER), 0)
    ImageDraw.Draw(hi).text((PAD * SUPER - l, PAD * SUPER - t), ch, font=font, fill=255)
    a = np.asarray(hi) > 127
    # edge pixels: inside pixels with an outside neighbour, and the reverse
    p = np.pad(a, 1)
    nb = p[:-2, 1:-1] ^ a | p[2:, 1:-1] ^ a | p[1:-1, :-2] ^ a | p[1:-1, 2:] ^ a
    ey, ex = np.nonzero(nb)
    ey = (ey + 0.5) / SUPER
    ex = (ex + 0.5) / SUPER
    w, h = -(-hi.width // SUPER), -(-hi.height // SUPER)
    out = np.zeros((h, w), dtype=np.uint8)
    for y in range(h):
        cy = y + 0.5
        cx = np.arange(w) + 0.5
        d = np.sqrt(((cx[:, None] - ex[None, :]) ** 2) + ((cy - ey[None, :]) ** 2)).min(axis=1)
        sy = min(int(cy * SUPER), a.shape[0] - 1)
        sx = np.minimum((cx * SUPER).astype(int), a.shape[1] - 1)
        inside = a[sy, sx]
        sd = np.where(inside, d, -d)  # positive inside
        out[y] = np.clip(128 + sd / SPREAD * 127, 0, 255).astype(np.uint8)
    return out.tobytes(), w, h, l / SUPER - PAD, adv, t / SUPER - PAD + dy


def glyph_rows(glyphs):
    return [f"  {{{off}, {w}, {h}, {left:.3f}f, {adv:.3f}f, {top:.3f}f}}," for off, w, h, left, adv, top in glyphs]


def data_rows(data):
    return ["  " + ",".join(str(v) for v in data[i : i + 24]) + "," for i in range(0, len(data), 24)]


def main_font():
    font = ImageFont.truetype(sys.argv[1] if len(sys.argv) > 1 else INTER, EM * SUPER)
    glyphs, data = [], bytearray()
    for ch in CHARS:
        f, w, h, left, adv, top = field(font, ch)
        glyphs.append((len(data) if f else 0, w, h, left, adv, top))
        data += f
    lines = [
        "/* Generated by tools/sdf-font.py, do not edit.",
        " * Signed distance fields of Inter Display ExtraBold glyphs.",
        " * Inter: (c) The Inter Project Authors, SIL Open Font License 1.1, https://rsms.me/inter/ */",
        f"#define SDF_EM {EM}",
        f"#define SDF_SPREAD {SPREAD}f",
        f'static const char SDF_CHARS[] = "{CHARS}";',
        "/* offset, w, h, left bearing, advance, top */",
        "struct sdf_glyph { unsigned int off; unsigned char w, h; float left, adv, top; };",
        "static const struct sdf_glyph SDF_GLYPHS[] = {",
        *glyph_rows(glyphs),
        "};",
        f"static const unsigned char SDF_DATA[{len(data)}] = {{",
        *data_rows(data),
        "};",
    ]
    Path(__file__).resolve().parent.parent.joinpath("sdf_font.h").write_text("\n".join(lines) + "\n")
    print(f"{len(glyphs)} glyphs, {len(data)} bytes")


STRING = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def unescape(lit):
    """A string literal's characters, with \\" and \\\\ read as one character."""
    return re.sub(r"\\(.)", r"\1", lit)


def wanted(sources):
    """Characters in the sources' string literals that sdf_font.h lacks."""
    chars = set()
    for src in sources:
        for m in STRING.finditer(Path(src).read_text(encoding="utf-8")):
            chars.update(c for c in unescape(m.group(1)) if c not in CHARS and (ord(c) > 127 or c.isprintable()))
    return sorted(chars)


def font_for(ch):
    """Which font draws a character: Inter for the scripts it has, else a Noto."""
    c = ord(ch)
    if c < 0x530 or 0x1E00 <= c < 0x2070:
        return "Inter"
    if 0x3040 <= c < 0x3100 or 0x31F0 <= c < 0x3200 or 0xFF65 <= c < 0xFFA0:
        return "Noto Sans JP"
    if 0x1100 <= c < 0x1200 or 0x3130 <= c < 0x3190 or 0xAC00 <= c < 0xD7B0:
        return "Noto Sans KR"
    return "Noto Sans SC"


def noto(family, chars, size):
    """A Noto family in ExtraBold with just these characters, from Google Fonts."""
    q = urllib.parse.urlencode({"family": f"{family}:wght@800", "text": "".join(chars)})
    with urllib.request.urlopen(f"https://fonts.googleapis.com/css2?{q}") as r:
        url = re.search(r"url\((https://[^)]+)\)", r.read().decode()).group(1)
    with urllib.request.urlopen(url) as r:
        return ImageFont.truetype(io.BytesIO(r.read()), size)


def extra(argv):
    out = Path(argv[0])
    chars = wanted(argv[1:])
    inter = ImageFont.truetype(INTER, EM * SUPER)
    fonts = {"Inter": (inter, 0)}
    for family in sorted({font_for(c) for c in chars} - {"Inter"}):
        font = noto(family, [c for c in chars if font_for(c) == family], round(EM * SUPER * EXTRA_SCALE))
        # both fonts are drawn from their ascender line; this puts the
        # glyphs' baseline on Inter's
        fonts[family] = (font, (inter.getmetrics()[0] - font.getmetrics()[0]) / SUPER)
    glyphs, data = [], bytearray()
    for ch in chars:
        font, dy = fonts[font_for(ch)]
        f, w, h, left, adv, top = field(font, ch, dy)
        glyphs.append((len(data) if f else 0, w, h, left, adv, top))
        data += f
    head = [
        "Generated by tools/sdf-font.py --extra, do not edit.",
        f"Signed distance fields of the {len(chars)} glyphs beyond sdf_font.h this game draws, from {', '.join(sorted({font_for(c) for c in chars}))} ExtraBold.",
        "Inter: (c) The Inter Project Authors; Noto Sans: (c) Google LLC; SIL Open Font License 1.1.",
    ]
    if out.suffix == ".rs":
        out.with_suffix(".bin").write_bytes(bytes(data))
        rows = [
            f"        wg::Glyph {{ off: {off}, w: {w}, h: {h}, left: {left:.3f}, adv: {adv:.3f}, top: {top:.3f} }},"
            for off, w, h, left, adv, top in glyphs
        ]
        lines = [
            *(f"// {line}" for line in head),
            "pub static GLYPHS: wg::Glyphs = wg::Glyphs {",
            "    chars: &[" + ", ".join(f"'\\u{{{ord(c):x}}}'" for c in chars) + "],",
            "    glyphs: &[",
            *rows,
            "    ],",
            f'    data: include_bytes!("{out.with_suffix(".bin").name}"),',
            "};",
        ]
    else:
        lines = [
            "/* " + "\n * ".join(head) + " */",
            "#define SDF_EXTRA 1",
            f"#define SDF_EXTRA_N {len(chars)}",
            "/* sorted, for a binary search */",
            "static const unsigned int SDF_EXTRA_CHARS[] = {" + ", ".join(f"0x{ord(c):x}" for c in chars) + "};",
            "static const struct sdf_glyph SDF_EXTRA_GLYPHS[] = {",
            *glyph_rows(glyphs),
            "};",
            f"static const unsigned char SDF_EXTRA_DATA[{max(len(data), 1)}] = {{",
            *data_rows(data or b"\0"),
            "};",
        ]
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(chars)} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    if sys.argv[1:2] == ["--extra"]:
        extra(sys.argv[2:])
    else:
        main_font()
